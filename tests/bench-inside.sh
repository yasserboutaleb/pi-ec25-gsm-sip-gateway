#!/bin/sh
# bench-inside.sh: runs INSIDE the bench image (tests/bench.sh). Never run it on a real gateway.
#
# The gateway image (gw-config, entrypoint, Asterisk 18 + chan_quectel) against the simulated
# modem in URC mode (EC25: RING and +QIND "ccinfo", the "dialing" URC BEFORE the OK of ATD),
# with AT+CLCC polling (MODEM_CLCC_POLL=1000). Voice over a serial port: the container has no
# sound card; the EC25 uses USB audio (UAC), a symmetric path in the driver (AT+QPCMV=1,2
# instead of 1,0). Numbers: French range reserved for fiction (06 39 98).
#
# Then the SIP side with the SMS and USSD handled by the driver (tests/fake_ec25.py: PDU mode,
# UCS2), against a softphone (tests/sip_client.py) and a SIP server in "register" and "ip" modes
# (tests/fake_registrar.py).
set -u
mkfifo /ctrl /ctrl-reg
: > /res/at.log
# in a loop: when Asterisk stops, the driver closes the ports and socat exits with them
( while :; do socat PTY,link=/dev/ttyQdata,raw,echo=0 EXEC:"python3 /t/fake_ec25.py /ctrl /res/at.log"; sleep 0.2; done ) &
( while :; do socat PTY,link=/dev/ttyQaudio,raw,echo=0 SYSTEM:"cat > /dev/null"; sleep 0.2; done ) &
sleep 2
echo "urc on" > /ctrl
# start with a call left open in the modem, as after an Asterisk crash during a call
echo "add_call 3 0 0" > /ctrl

# settings of a user: softphone on the loopback, incoming GSM calls answered by the echo test
export MODEM_DATA_PORT=/dev/ttyQdata MODEM_AUDIO=serial MODEM_AUDIO_PORT=/dev/ttyQaudio MODEM_CLCC_POLL=1000 \
       SOFTPHONE_PASSWORD=bench-password SOFTPHONE_NETWORK=127.0.0.0/8 GSM_ECHO_TEST=1
/usr/local/sbin/entrypoint.sh > /res/asterisk.out 2>&1 &
astrx() { asterisk -rx "$1" 2>&1; }
for _ in $(seq 1 60); do astrx 'core waitfullybooted' >/dev/null 2>&1 && break; sleep 1; done

PASS=0; FAIL=0
check() { if eval "$2"; then echo "PASS  $1"; PASS=$((PASS+1)); else echo "FAIL  $1"; FAIL=$((FAIL+1)); fi; }
dev_free() { astrx 'quectel show devices' | grep -q -i ' Free '; }
wait_free() { t=0; while [ "$t" -lt "$1" ] && ! dev_free; do sleep 1; t=$((t+1)); done; echo "$t"; }
calls_empty() { echo dump > /ctrl; sleep 1; grep 'CALLS' /res/at.log | tail -1 | grep -q 'CALLS 0$'; }
dial_wait() { for _ in $(seq 1 15); do grep -q "ATD$1" /res/at.log && break; sleep 1; done; }
chan() { astrx 'core show channels concise' | grep -o -m1 '^Quectel/quectel0[^!]*'; }
chan_hangup() { ch=$(chan); [ -n "$ch" ] && astrx "channel request hangup $ch" >/dev/null; }
ata_wait() { for _ in $(seq 1 20); do [ "$(grep -c ' ATA$' /res/at.log)" -gt "$1" ] && break; sleep 1; done; }
q3() { grep -c -E 'AT\+QHUP=[0-9]+,3$' /res/at.log; }
unknown() { grep -a -c 'unknown call idx' /res/asterisk.out; }

t=$(wait_free 90)
check "configuration generated by gw-config, Asterisk started by the entrypoint" "grep -q 'gw-config: configuration generated' /res/asterisk.out && astrx 'module show like chan_quectel' | grep -q chan_quectel"
loaded() {
	for c in from-gsm from-sip sms-out msg-to-sip; do astrx "dialplan show $c" | grep -q 'extension' || return 1; done
	astrx 'pjsip show endpoint gsm' | grep -q 'Endpoint:  gsm'
}
check "dialplan and SIP endpoint loaded (from-gsm, from-sip, sms-out, msg-to-sip, softphone gsm)" loaded
# The module folder depends on the architecture (x86_64-linux-gnu, aarch64-linux-gnu): Asterisk
# must use the one of the package, where the driver is installed
moddir_ok() {
	d=$(astrx 'core show settings' | sed -n 's/^ *Module directory: *//p')
	[ -n "$d" ] && [ -f "$d/chan_quectel.so" ] && ! grep -q '^\[directories\]' /etc/asterisk/asterisk.conf
}
check "module folder of the package for this architecture, with the driver in it" moddir_ok
# Jitter buffer on the SIP side before Dial, both directions (USB audio needs a steady voice)
jb_ok() {
	astrx 'module show like func_jitterbuffer' | grep -q 'Running' && astrx 'module show like app_stack' | grep -q 'Running' \
		&& astrx 'dialplan show net-jb' | grep -q 'JITTERBUFFER(${NET_JB})' \
		&& astrx 'dialplan show from-gsm' | grep -q 'b(net-jb^s^1)' && astrx 'dialplan show from-sip' | grep -q 'Gosub(net-jb,s,1)'
}
check "jitter buffer set on the SIP side of calls (JITTER_BUFFER, func_jitterbuffer loaded)" jb_ok
check "start with a call left open: call hung up, voice enabled again, line free (${t} s)" "grep -q -E 'AT\+QHUP=21,3$' /res/at.log && [ \$(grep -c 'AT+QPCMV=1,0' /res/at.log) -ge 2 ] && dev_free && calls_empty"
check "health check: healthy" "gw-check --health >/dev/null"
check "ccinfo URCs enabled (AT+QINDCFG ccinfo)" "grep -q 'AT+QINDCFG=.ccinfo.,1' /res/at.log"
check "AT+CLCC polling active" "[ \$(grep -c 'AT+CLCC' /res/at.log) -ge 5 ]"

u0=$(unknown); q0=$(q3)
astrx "channel originate Quectel/quectel0/0639980001 application Wait 20" >/dev/null
dial_wait 0639980001; sleep 4
check "outgoing: ccinfo \"dialing\" before the OK of ATD, call matched and in progress" "chan | grep -q . && grep -q 'URC ccinfo 3 2' /res/at.log && [ \$(unknown) -eq $u0 ]"
echo "answer_remote" > /ctrl; sleep 3
check "outgoing: answered" "astrx 'core show channels concise' | grep '^Quectel/quectel0' | grep -q '!Up!'"
chan_hangup; t=$(wait_free 10)
check "outgoing: hung up by its real index, line free (${t} s)" "[ \$(q3) -gt $q0 ] && dev_free && calls_empty && [ \$(unknown) -eq $u0 ]"

# through the dialplan, as a call from the softphone or the server (context from-sip)
astrx "channel originate Local/0639980002@from-sip application Wait 20" >/dev/null
dial_wait 0639980002; sleep 3
check "SIP -> GSM through the dialplan (from-sip): number dialled" "grep -q 'ATD0639980002;' /res/at.log && chan | grep -q ."
echo "remote_hangup" > /ctrl; t=$(wait_free 10)
check "SIP -> GSM: remote hang-up, line free (${t} s), masked number in the log" "dev_free && calls_empty && grep -a -q 'call out 0639\.\.\.' /res/asterisk.out"

e0=$(grep -a -c 'Error sending hangup' /res/asterisk.out)
astrx "channel originate Quectel/quectel0/0639980003 application Wait 20" >/dev/null
dial_wait 0639980003; chan_hangup; t=$(wait_free 10)
check "cancelled at once: hung up without error, line free (${t} s)" "[ \$(grep -a -c 'Error sending hangup' /res/asterisk.out) -eq $e0 ] && dev_free && calls_empty"

a0=$(grep -c ' ATA$' /res/at.log)
echo "ring +33639980004" > /ctrl
ata_wait "$a0"; sleep 3
check "incoming (RING + ccinfo): answered by the echo test (ATA)" "[ \$(grep -c ' ATA$' /res/at.log) -gt $a0 ] && chan | grep -q ."
echo "remote_hangup" > /ctrl; t=$(wait_free 10)
check "incoming: remote hang-up, line free (${t} s), masked number in the log" "dev_free && calls_empty && grep -a -q 'call in +336\.\.\. ECHO' /res/asterisk.out"

echo "refuse_hangup 1 qhup" > /ctrl
c0=$(grep -c 'AT+CHUP' /res/at.log)
astrx "channel originate Quectel/quectel0/0639980005 application Wait 20" >/dev/null
dial_wait 0639980005; sleep 3; chan_hangup; t=$(wait_free 25)
check "hang-up refused by the modem: retried with AT+CHUP, line free (${t} s)" "[ \$(grep -c 'AT+CHUP' /res/at.log) -gt $c0 ] && dev_free && calls_empty"

astrx "channel originate Quectel/quectel0/0639980006 application Wait 30" >/dev/null
dial_wait 0639980006; sleep 2; echo "answer_remote" > /ctrl; sleep 3
a0=$(grep -c ' ATA$' /res/at.log)
printf 'remote_hangup\nring +33639980007\n' > /ctrl
ata_wait "$a0"; sleep 3
echo "remote_hangup" > /ctrl; t=$(wait_free 10)
check "end of call and incoming call at the same time, same index: new call answered, line free" "[ \$(grep -c ' ATA$' /res/at.log) -gt $a0 ] && dev_free && calls_empty && ! grep -a -q 'direction mismatch' /res/asterisk.out"

check "never AT+QHUP on a provisional (31) or data (1, 2) index" "! grep -q -E 'AT\+QHUP=[0-9]+,(1|2|31)$' /res/at.log"
check "no gateway call hung up as \"unknown\" outside the start" "[ \$(unknown) -le 1 ]"
check "device state of a registered module shown" "astrx 'quectel show device state quectel0' | grep -q -i 'GSM Registration Status'"

# ---------------------------------------------------------------- softphone: SIP, SMS, USSD
# Like a real softphone, the From user is the account (gsm), not the name of the endpoint.
wait_grep() { for _ in $(seq 1 "$3"); do grep -a -q -F -- "$2" "$1" 2>/dev/null && return 0; sleep 1; done; return 1; }
SIPC="python3 /t/sip_client.py --user gsm --password bench-password"
$SIPC register > /res/sip-register.out 2>&1
check "softphone: REGISTER with digest authentication, account gsm as From user" "grep -q 'REGISTER -> 200' /res/sip-register.out"
$SIPC echo 9600 > /res/sip-echo.out 2>&1; echo "rc=$?" >> /res/sip-echo.out
check "softphone: echo test 9600 (no GSM call), RTP echoed back, BYE" "grep -q 'INVITE 9600 -> 200' /res/sip-echo.out && grep -q 'rc=0' /res/sip-echo.out"

n0=$(grep -c -E 'AT\+(CHUP|QHUP)' /res/at.log)
$SIPC call 0639980011 --wait 40 --hold 3 > /res/sip-call.out 2>&1 &
SPID=$!
dial_wait 0639980011
check "softphone -> GSM: number dialled (ATD)" "grep -q 'ATD0639980011;' /res/at.log"
sleep 2; echo "answer_remote" > /ctrl
wait $SPID; echo "rc=$?" >> /res/sip-call.out
t=$(wait_free 10)
check "softphone -> GSM: answered (200), BYE from the softphone, GSM call released, line free (${t} s)" "grep -q 'INVITE 0639980011 -> 200' /res/sip-call.out && grep -q 'rc=0' /res/sip-call.out && [ \$(grep -c -E 'AT\+(CHUP|QHUP)' /res/at.log) -gt $n0 ] && dev_free && calls_empty"

# the softphone stays registered and receives the SMS and USSD replies as MESSAGE
python3 /t/sip_client.py listen --user gsm --password bench-password --port 5072 --wait 150 > /res/sip-listen.out 2>&1 &
LPID=$!
wait_grep /res/sip-listen.out 'REGISTER -> 200' 10

# SMS out: the text must reach the modem unchanged, never interpreted by the dialplan
TXT1='Hello é ; "quote" ${EXTEN} $(id) (a,b) | {end}'
$SIPC message 0639980012 "$TXT1" > /res/sip-message1.out 2>&1
wait_grep /res/at.log 'SMS-OUT to=0639980012 ' 15
printf '%s\n' "SMS-OUT to=0639980012 dcs=0 vp=167 part=1/1 ref=- text=$TXT1" > /res/expect-sms1.txt
check "SMS out: softphone MESSAGE accepted (202), sent with AT+CMGS" "grep -q 'MESSAGE 0639980012 -> 202' /res/sip-message1.out && grep -q 'AT+CMGS=' /res/at.log"
check "SMS out: text unchanged (quotes, \${...}, \$(...), commas), GSM 7-bit, validity 1 day" "grep -q -F -f /res/expect-sms1.txt /res/at.log"
TXT2='Łódź: it works ✓'
$SIPC message +33639980013 "$TXT2" > /res/sip-message2.out 2>&1
wait_grep /res/at.log 'SMS-OUT to=+33639980013 ' 15
printf '%s\n' "SMS-OUT to=+33639980013 dcs=8 vp=167 part=1/1 ref=- text=$TXT2" > /res/expect-sms2.txt
check "SMS out: international number, characters outside GSM 7-bit sent as UCS2" "grep -q -F -f /res/expect-sms2.txt /res/at.log"
TXT3=$(printf 'Long message, part of a test of the bench number %02d. ' $(seq 1 5)); TXT3=${TXT3% }
$SIPC message 0639980014 "$TXT3" > /res/sip-message3.out 2>&1
for _ in $(seq 1 20); do [ "$(grep -c 'SMS-OUT to=0639980014 ' /res/at.log)" -ge 2 ] && break; sleep 1; done
grep 'SMS-OUT to=0639980014 ' /res/at.log | sed 's/^.* text=//' | tr -d '\n' > /res/sms3-joined.txt
check "SMS out: long text (${#TXT3} characters) sent in 2 concatenated parts, text unchanged" "[ \$(grep -c 'SMS-OUT to=0639980014 dcs=0 vp=167 part=[12]/2 ' /res/at.log) -eq 2 ] && [ \"\$(cat /res/sms3-joined.txt)\" = \"\$TXT3\" ]"

# SMS in: +CMTI, read (AT+CMGR), deleted (AT+CMGD), then MESSAGE to the softphone
echo "sms +33639980015 Meet at Café Müller, 18:30, door B {ok}" > /ctrl
wait_grep /res/sip-listen.out 'MESSAGE-IN from=<sip:+33639980015@' 15
check "SMS in: announced (+CMTI), read (AT+CMGR) then deleted (AT+CMGD)" "grep -q 'AT+CMGR=1' /res/at.log && grep -q 'AT+CMGD=1' /res/at.log"
check "SMS in -> softphone MESSAGE from the sender's number, GSM 7-bit text unchanged" "grep -F 'MESSAGE-IN from=<sip:+33639980015@' /res/sip-listen.out | grep -q -F 'body=Meet at Café Müller, 18:30, door B {ok}'"
echo "sms 0639980016 It works ✓ 1€" > /ctrl
wait_grep /res/sip-listen.out 'MESSAGE-IN from=<sip:0639980016@' 15
check "SMS in: UCS2 text unchanged" "grep -F 'MESSAGE-IN from=<sip:0639980016@' /res/sip-listen.out | grep -q -F 'body=It works ✓ 1€'"
echo "sms_long +33639980017 $TXT3" > /ctrl
wait_grep /res/sip-listen.out 'MESSAGE-IN from=<sip:+33639980017@' 20
check "SMS in: 2 concatenated parts (2 s apart) -> one MESSAGE with the whole text" "[ \$(grep -c 'MESSAGE-IN from=<sip:+33639980017@' /res/sip-listen.out) -eq 1 ] && grep -F 'MESSAGE-IN from=<sip:+33639980017@' /res/sip-listen.out | grep -q -F \"body=\$TXT3\""
# both parts announced at once: up to chan_quectel 6e11254, a +CMTI received while another SMS was
# read was dropped until the next start of the driver; now queued and read next
echo "sms_burst +33639980018 $TXT3" > /ctrl
wait_grep /res/sip-listen.out 'MESSAGE-IN from=<sip:+33639980018@' 10
check "SMS in: 2 parts announced at once -> both read, one MESSAGE with the whole text" "grep -q 'AT+CMGR=2' /res/at.log && [ \$(grep -c 'MESSAGE-IN from=<sip:+33639980018@' /res/sip-listen.out) -eq 1 ] && grep -F 'MESSAGE-IN from=<sip:+33639980018@' /res/sip-listen.out | grep -q -F \"body=\$TXT3\""

# invalid numbers: refused, never passed to Dial or to the driver ("&" or "," would add a channel
# or options)
$SIPC message '0639980030&x' 'text' > /res/sip-message-bad.out 2>&1
$SIPC call '0639980031&Local/x' --wait 10 > /res/sip-call-bad.out 2>&1
sleep 2
check "invalid number: MESSAGE and call refused, nothing sent to the modem" "! grep -q -E 'SMS-OUT to=063998003[01]|ATD063998003[01]' /res/at.log && ! grep -q 'INVITE 0639980031&Local/x -> 200' /res/sip-call-bad.out"

# USSD: *100# dialled from the softphone (# written %23 in the SIP URI), reply as a MESSAGE
$SIPC call '*100%23' --wait 20 --vanish > /res/sip-ussd.out 2>&1
wait_grep /res/sip-listen.out 'MESSAGE-IN from=<sip:ussd@' 15
check "USSD: *100# dialled from the softphone, sent to the modem (AT+CUSD)" "grep -q 'INVITE \*100%23 -> 200' /res/sip-ussd.out && grep -q 'USSD-REQ \*100#' /res/at.log"
check "USSD: reply -> softphone MESSAGE from ussd, text unchanged" "grep -F 'MESSAGE-IN from=<sip:ussd@' /res/sip-listen.out | grep -q -F \"body=Balance: 12.50 EUR, valid until 31/12, café included\""
# USSD from a local tool (ussd-console context, no SIP call); USSD_LOG_TEXT=0: reply text not logged
astrx 'channel originate Local/s@ussd-console application QUECTEL_SEND_USSD quectel0,*101#' >/dev/null
wait_grep /res/at.log 'USSD-REQ *101#' 15
sleep 3
check "USSD from a local tool (ussd-console), reply text not in the log by default" "grep -q 'USSD-REQ \*101#' /res/at.log && ! grep -a -q 'Got USSD type' /res/asterisk.out"
kill $LPID 2>/dev/null
check "SMS and USSD: masked numbers and USSD codes in the log" "grep -a -q 'sms out 0639\.\.\.' /res/asterisk.out && grep -a -q 'sms in +336\.\.\.' /res/asterisk.out && grep -a -q 'ussd request \*100\.\.\. 5 chars' /res/asterisk.out && ! grep -a -q 'ussd request \*100#' /res/asterisk.out"

# ---------------------------------------------------------------- SIP server, "register" mode
# The gateway registers with its account (password with & and |), sends the incoming GSM calls and
# SMS to extension 102 (caller's number as display name), and accepts the server's calls.
restart_gw() {
	astrx 'core stop now' >/dev/null 2>&1
	for _ in $(seq 1 15); do pgrep -x asterisk >/dev/null || break; sleep 1; done
	# new simulated ports: the old pseudo-terminals keep the exclusive mode set by the driver
	pkill -f 'socat PTY,link=/dev/ttyQ'; sleep 1
	env "$@" /usr/local/sbin/entrypoint.sh >> /res/asterisk.out 2>&1 &
	for _ in $(seq 1 60); do astrx 'core waitfullybooted' >/dev/null 2>&1 && break; sleep 1; done
	wait_free 60 >/dev/null
	echo "urc on" > /ctrl  # the simulated modem was restarted with the ports
}
: > /res/registrar.log
python3 /t/fake_registrar.py 5080 gw 'gw&pass1|x' /res/registrar.log /ctrl-reg &
REG=$!
restart_gw SERVER_ENABLED=1 SERVER_MODE=register SERVER_HOST=127.0.0.1 SERVER_PORT=5080 SERVER_USERNAME=gw \
	'SERVER_PASSWORD=gw&pass1|x' SERVER_EXTENSION=102 GSM_ECHO_TEST=0 USSD_REPLY_FILE=/run/gsm-gateway/ussd-reply
for i in $(seq 1 30); do astrx 'pjsip show registrations' | grep 'server-reg' | grep -q ' Registered' && break; sleep 1; done
check "SIP_BIND=0.0.0.0 (default): no media_address on the endpoints" "astrx 'pjsip show endpoint server' | grep -q -E '^ *media_address +: *$' && ! grep -q media_address /etc/asterisk/pjsip.conf"
check "register mode: registered after digest authentication (${i} s)" "grep -q 'REGISTER-401' /res/registrar.log && grep -q 'REGISTER-200' /res/registrar.log"
k0=$(grep -c -E 'AT\+QHUP=17,' /res/at.log)
echo "ring +33639980020" > /ctrl
wait_grep /res/registrar.log 'INVITE ruri=sip:102@127.0.0.1:5080' 20
for _ in $(seq 1 20); do [ "$(grep -c -E 'AT\+QHUP=17,' /res/at.log)" -gt "$k0" ] && break; sleep 1; done
check "register mode: incoming GSM call to extension 102 (account gw, number in P-Asserted-Identity), busy -> GSM rejected as busy (17)" "grep 'INVITE ruri=sip:102@127.0.0.1:5080' /res/registrar.log | grep -q 'sip:gw@' && grep 'INVITE ruri=sip:102@' /res/registrar.log | grep -q '+33639980020' && [ \$(grep -c -E 'AT\+QHUP=17,' /res/at.log) -gt $k0 ]"
echo "remote_hangup" > /ctrl; wait_free 10 >/dev/null
echo "sms +33639980021 Message to the server" > /ctrl
wait_grep /res/registrar.log 'MESSAGE-200' 15
check "register mode: SMS in -> authenticated MESSAGE to 102 (sender as display name, account gw)" "grep -q 'MESSAGE-401' /res/registrar.log && grep 'MESSAGE-200' /res/registrar.log | grep -q -E 'ruri=sip:102@127.0.0.1(:5080)? .*[+]33639980021.? <sip:gw@127.0.0.1>' && grep 'MESSAGE-200' /res/registrar.log | grep -q 'body=Message to the server'"
echo "message 0639980026 Sent by the server, café" > /ctrl-reg
wait_grep /res/at.log 'SMS-OUT to=0639980026 ' 15
check "register mode: MESSAGE from the server on the registered line (line parameter) -> SMS" "grep -q 'SMS-OUT to=0639980026 .* text=Sent by the server, café' /res/at.log"
echo "message_noline 0639980027 without line" > /ctrl-reg
sleep 3
check "register mode: MESSAGE without the line parameter refused, no SMS" "grep -q 'MESSAGE-OUT ruri=sip:0639980027@' /res/registrar.log && ! grep -q 'SMS-OUT to=0639980027' /res/at.log"
# anyone who knows the name of the server's endpoint ("server") puts it in From, without password
# or line: must not be taken for the server (Asterisk also identifies endpoints by the From user)
python3 /t/sip_client.py message 0639980028 'spoofed' --user server --port 5073 > /res/sip-spoof-msg.out 2>&1
python3 /t/sip_client.py call 0639980029 --user server --port 5073 --wait 8 > /res/sip-spoof-call.out 2>&1
sleep 2
check "register mode: From user \"server\" without password or line refused (no SMS, no call)" "! grep -q -E 'SMS-OUT to=0639980028|ATD0639980029' /res/at.log && ! grep -q -E ' -> 20[02]' /res/sip-spoof-msg.out /res/sip-spoof-call.out"
wait_free 20 >/dev/null   # the line may still be releasing the previous call
echo "invite 0639980022" > /ctrl-reg
dial_wait 0639980022
check "register mode: call from the server (registered line) dialled to GSM" "grep -q 'ATD0639980022;' /res/at.log"
echo "cancel" > /ctrl-reg; t=$(wait_free 10)
check "register mode: call cancelled by the server, line free (${t} s)" "dev_free && calls_empty"
# USSD_REPLY_FILE: a menu reply (type 1) then the final reply replace the file in turn (type,
# description, text); the text never goes to the log (USSD_LOG_TEXT=0 here)
F=/run/gsm-gateway/ussd-reply
echo "ussd_type 1" > /ctrl; echo "ussd_reply Menu: 1 Recharge, 2 Balance" > /ctrl; sleep 1
rm -f $F
astrx 'channel originate Local/s@ussd-console application QUECTEL_SEND_USSD quectel0,*111#' >/dev/null
for _ in $(seq 1 15); do [ -s $F ] && break; sleep 1; done; sleep 1
cp $F /res/ussd-reply-1.txt 2>/dev/null
echo "ussd_type 0" > /ctrl; echo "ussd_reply Recharge done: 5.00, café" > /ctrl; sleep 1
rm -f $F
astrx 'channel originate Local/s@ussd-console application QUECTEL_SEND_USSD quectel0,1' >/dev/null
for _ in $(seq 1 15); do [ -s $F ] && break; sleep 1; done; sleep 1
cp $F /res/ussd-reply-2.txt 2>/dev/null
printf '1\nUSSD Request\nMenu: 1 Recharge, 2 Balance' > /res/expect-ussd-1.txt
printf '0\nUSSD Notify\nRecharge done: 5.00, café' > /res/expect-ussd-2.txt
echo "ussd_reply Balance: 12.50 EUR, valid until 31/12, café included" > /ctrl
check "USSD_REPLY_FILE: menu (type 1) then final reply written to the file, folder 700, nothing in the log" "cmp -s /res/expect-ussd-1.txt /res/ussd-reply-1.txt && cmp -s /res/expect-ussd-2.txt /res/ussd-reply-2.txt && [ \$(stat -c %a /run/gsm-gateway) = 700 ] && ! grep -a -q -E 'Recharge|Menu: 1' /res/asterisk.out"
kill $REG 2>/dev/null

# ---------------------------------------------------------------- SIP server, "ip" mode
# Trusted peer identified by its address, no password; softphone off.
: > /res/registrar-ip.log
python3 /t/fake_registrar.py 5080 - - /res/registrar-ip.log /ctrl-reg &
REG=$!
restart_gw SERVER_ENABLED=1 SERVER_MODE=ip SERVER_HOST=127.0.0.1 SERVER_PORT=5080 SERVER_EXTENSION=102 \
	SERVER_LOCAL_ADDRESS=127.0.0.1 SOFTPHONE_PASSWORD= GSM_ECHO_TEST=0 USSD_LOG_TEXT=1 'DIAL_ALLOW=^([0-9]{2,3}|0[5-7][0-9]{8}|[+]33[67][0-9]{8})$' SIP_BIND=127.0.0.1
# SIP_BIND=127.0.0.1: SDP and RTP of the endpoints from that address (several gateways on one host)
check "SIP_BIND set to one address: media_address and bind_rtp_to_media_address on the server endpoint" "astrx 'pjsip show endpoint server' | grep -q -E '^ *media_address +: 127\.0\.0\.1' && astrx 'pjsip show endpoint server' | grep -q -E '^ *bind_rtp_to_media_address +: true'"
astrx 'channel originate Local/s@ussd-console application QUECTEL_SEND_USSD quectel0,*102#' >/dev/null
wait_grep /res/asterisk.out 'Got USSD type' 15
check "USSD_LOG_TEXT=1: reply text in the log, in the driver's format (local tools)" "grep -a -q \"Got USSD type 0 '[^']*': \[Balance: 12.50 EUR, valid until 31/12, café included\]\" /res/asterisk.out"
echo "sms +33639980023 Message in ip mode" > /ctrl
wait_grep /res/registrar-ip.log 'from=<sip:+33639980023@127.0.0.1>' 15
check "ip mode: SMS in -> MESSAGE to 102, sender's number as From user" "grep 'MESSAGE-200' /res/registrar-ip.log | grep -q 'from=<sip:+33639980023@127.0.0.1>' && grep 'MESSAGE-200' /res/registrar-ip.log | grep -q 'body=Message in ip mode'"
python3 /t/sip_client.py message 0639980024 'From the server' --user 102 > /res/sip-message-ip.out 2>&1
wait_grep /res/at.log 'SMS-OUT to=0639980024 ' 15
check "ip mode: MESSAGE from the server (no password) -> SMS" "grep -q 'MESSAGE 0639980024 -> 202' /res/sip-message-ip.out && grep -q 'SMS-OUT to=0639980024 .* text=From the server' /res/at.log"
echo "invite 0639980025" > /ctrl-reg
dial_wait 0639980025
check "ip mode: call from the server dialled to GSM" "grep -q 'ATD0639980025;' /res/at.log"
echo "cancel" > /ctrl-reg; wait_free 10 >/dev/null
# DIAL_ALLOW (short numbers, national mobiles and +33 mobiles here, with a {2,3} comma): a number
# outside the pattern is refused, call and SMS
python3 /t/sip_client.py message +88212345678 'premium' --user 102 > /res/sip-deny-msg.out 2>&1
python3 /t/sip_client.py call +88212345679 --user 102 --wait 6 > /res/sip-deny-call.out 2>&1
sleep 2
check "DIAL_ALLOW: call and SMS to a number outside the pattern refused, nothing sent to the modem" "! grep -q -E 'SMS-OUT to=\+8821234567|ATD\+8821234567' /res/at.log && [ \$(grep -a -c 'not allowed by DIAL_ALLOW' /res/asterisk.out) -ge 2 ]"
kill $REG 2>/dev/null
# "docker compose run --rm gateway gw-config check": the entrypoint runs the command instead of the
# gateway; check builds the whole configuration in a temporary folder (COUNTRY without tones is
# refused) and never touches the configuration of the running Asterisk
m0=$(md5sum /etc/asterisk/pjsip.conf /etc/asterisk/extensions.conf)
check "entrypoint with a command: gw-config check runs, valid settings accepted, bad DIAL_ALLOW and COUNTRY=xx refused, running configuration untouched" "/usr/local/sbin/entrypoint.sh gw-config check >/dev/null 2>&1 && DIAL_ALLOW='^(0[67]|[+]33[67])[0-9]{8}\$' /usr/local/sbin/entrypoint.sh gw-config check >/dev/null 2>&1 && ! DIAL_ALLOW='0;6' /usr/local/sbin/entrypoint.sh gw-config check >/dev/null 2>&1 && ! DIAL_ALLOW='(0' /usr/local/sbin/entrypoint.sh gw-config check >/dev/null 2>&1 && ! COUNTRY=xx /usr/local/sbin/entrypoint.sh gw-config check >/dev/null 2>&1 && [ \"\$(md5sum /etc/asterisk/pjsip.conf /etc/asterisk/extensions.conf)\" = \"$m0\" ] && [ \$(pgrep -c -x asterisk) -eq 1 ]"
check "full numbers never in the log (GSM_VERBOSE=0)" "! grep -a -q -E '06399800[0-9][0-9]|336399800[0-9][0-9]' /res/asterisk.out"
check "Asterisk still running (no crash)" "pgrep -x asterisk >/dev/null"

# without a modem, as a host whose module is missing or not yet registered (registration state
# -1): "quectel show device state" crashed Asterisk on 64-bit hosts with chan_quectel up to 3ee2fd6
astrx 'core stop now' >/dev/null 2>&1
for _ in $(seq 1 10); do pgrep -x asterisk >/dev/null || break; sleep 1; done
MODEM_DATA_PORT=/dev/ttyQnone /usr/local/sbin/entrypoint.sh > /res/asterisk-nomodem.out 2>&1 &
for _ in $(seq 1 60); do astrx 'core waitfullybooted' >/dev/null 2>&1 && break; sleep 1; done
for _ in 1 2 3; do astrx 'quectel show device state quectel0' > /res/device-state-nomodem.txt; sleep 1; done
check "no modem: \"quectel show device state\" answers, Asterisk still running" "grep -q -i 'GSM Registration Status' /res/device-state-nomodem.txt && pgrep -x asterisk >/dev/null"
check "no modem: health check unhealthy (module not connected)" "! gw-check --health >/dev/null"

echo "Result: $PASS PASS / $FAIL FAIL"
astrx 'core stop now' >/dev/null 2>&1; sleep 2
exit $FAIL
